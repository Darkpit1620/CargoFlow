# Only columns a member of staff is permitted to populate. Tracking numbers are
# generated by the model, never accepted from an uploaded spreadsheet.
CSV_COLUMNS = (
    'sender_name', 'recipient_name', 'recipient_phone', 'recipient_email',
    'origin', 'destination', 'weight_kg', 'delivery_fee',
    'expected_delivery', 'notes',
)
MANDATORY_COLUMNS = ('sender_name', 'recipient_name', 'recipient_phone',
                     'origin', 'destination', 'weight_kg')
MAX_FILE_BYTES = 1024 * 1024
MAX_SHIPMENTS = 200
OPEN_STATUSES = (
    Shipment.Status.PENDING, Shipment.Status.PICKED_UP,
    Shipment.Status.IN_TRANSIT, Shipment.Status.OUT_FOR_DELIVERY,
    Shipment.Status.FAILED,
)


def tracking_link(request, shipment):
    path = reverse('track-shipment') + '?' + urlencode({'code': shipment.tracking_number})
    return request.build_absolute_uri(path)


@staff_required
@require_GET
def shipping_label(request, pk):
    shipment = get_object_or_404(Shipment.objects.select_related('driver'), pk=pk)
    return render(request, 'shipping_tools/label.html', {
        'shipment': shipment,
        'tracking_link': tracking_link(request, shipment),
    })


@staff_required
@require_GET
def shipping_qr(request, pk):
    shipment = get_object_or_404(Shipment, pk=pk)
    qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M,
                       box_size=8, border=2)
    qr.add_data(tracking_link(request, shipment))
    qr.make(fit=True)
    img = qr.make_image(image_factory=SvgPathImage)
    svg_stream = io.BytesIO()
    img.save(svg_stream)
    response = HttpResponse(svg_stream.getvalue(), content_type='image/svg+xml')
    response['X-Content-Type-Options'] = 'nosniff'
    response['Cache-Control'] = 'private, max-age=300'
    return response


@staff_required
@require_GET
def import_template(request):
    response = HttpResponse(content_type='text/csv; charset=utf-8')
    response['Content-Disposition'] = 'attachment; filename="cargoflow_import_template.csv"'
    response.write('\ufeff')
    writer = csv.writer(response)
    writer.writerow(CSV_COLUMNS)
    writer.writerow([
        'Example Sender', 'Example Recipient', '0700000000', '',
        'Nairobi', 'Mombasa', '2.50', '450.00', '2026-12-15', '',
    ])
    return response


def _validate_import(upload):
    """Return (clean forms, errors), without writing any database records."""
    if upload is None:
        return [], ['Select a CSV file to upload.']
    if upload.size > MAX_FILE_BYTES:
        return [], ['The CSV file is too large. Maximum size is 1 MB.']
    if not upload.name.lower().endswith('.csv'):
        return [], ['Please upload a .csv file.']
    try:
        text = upload.read().decode('utf-8-sig')
    except UnicodeDecodeError:
        return [], ['Save the CSV as UTF-8 and try again.']
    if '\x00' in text:
        return [], ['CSV contains invalid characters.']
    try:
        reader = csv.DictReader(io.StringIO(text, newline=''), strict=True)
        if not reader.fieldnames:
            return [], ['CSV is empty.']
        header = [h.strip() for h in reader.fieldnames]
        if len(set(header)) != len(header):
            return [], ['The CSV has duplicate column names.']
        missing = [h for h in MANDATORY_COLUMNS if h not in header]
        unexpected = [h for h in header if h not in CSV_COLUMNS]
        if missing:
            return [], ['Missing required columns: ' + ', '.join(missing)]
        if unexpected:
            return [], ['Unknown columns: ' + ', '.join(unexpected)]
        forms = []
        errors = []
        for row_no, raw in enumerate(reader, start=2):
            if row_no > MAX_SHIPMENTS + 1:
                return [], [f'Import limit is {MAX_SHIPMENTS} shipments per file.']
            if None in raw:  # Additional cells after the last named column
                errors.append(f'Row {row_no}: too many cells for the header.')
                continue
            values = {key.strip(): (value or '').strip() for key, value in raw.items()}
            if not any(values.values()):
                continue
            data = {key: values.get(key, '') for key in CSV_COLUMNS}
            # Each row uses the same business validation as the New Shipment form.
            form = ShipmentForm(data=data)
            if form.is_valid():
                forms.append(form)
            else:
                for field, field_errors in form.errors.items():
                    for error in field_errors:
                        errors.append(f'Row {row_no}, {field}: {error}')
            if len(errors) >= 25:
                errors.append('Too many errors. Fix the CSV and retry.')
                return [], errors
        if not forms and not errors:
            errors.append('CSV has no shipments to import.')
        return forms, errors
    except (csv.Error, TypeError, ValueError) as exc:
        return [], ['Unable to read the CSV. Please check the format and try again.']


@staff_required
def bulk_import(request):
    errors = []
    if request.method == 'POST':
        forms, errors = _validate_import(request.FILES.get('file'))
        if not errors:
            with transaction.atomic():
                for form in forms:
                    shipment = form.save(commit=False)
                    shipment.created_by = request.user
                    shipment.save()  # creates initial tracking event
                    event = shipment.events.first()
                    if event:
                        event.updated_by = request.user
                        event.save(update_fields=['updated_by'])
            messages.success(request, f'Imported {len(forms)} shipments. All tracking codes were generated automatically.')
            return redirect('shipment-list')
    return render(request, 'shipping_tools/import.html', {
        'errors': errors, 'max_shipments': MAX_SHIPMENTS,
    })


def _chosen_driver(request):
    raw_id = request.GET.get('driver', '').strip()
    if not raw_id:
        return None, None
    if not raw_id.isdecimal():
        return None, 'Please choose a valid driver.'
    driver = Driver.objects.filter(pk=int(raw_id)).first()
    if driver is None:
        return None, 'Driver not found.'
    return driver, None


@staff_required
@require_GET
def driver_manifest(request):
    driver, error = _chosen_driver(request)
    shipments = None
    if driver is not None:
        shipments = Shipment.objects.filter(
            driver=driver, status__in=OPEN_STATUSES,
        ).order_by('destination', 'tracking_number')[:500]
    return render(request, 'shipping_tools/manifest.html', {
        'drivers': Driver.objects.order_by('full_name'),
        'selected_driver': driver, 'shipments': shipments,
        'error': error,
    })


def _excel_safe(value):
    text = str(value if value is not None else '')
    if text.lstrip().startswith(('=', '+', '-', '@', '\t', '\r', '\n')):
        return "'" + text
    return text


@staff_required
@require_GET
def export_manifest(request):
    driver, error = _chosen_driver(request)
    if error or driver is None:
        return HttpResponseBadRequest(error or 'Choose a driver before exporting.')
    shipments = Shipment.objects.filter(driver=driver, status__in=OPEN_STATUSES).order_by(
        'destination', 'tracking_number',
    )
    response = HttpResponse(content_type='text/csv; charset=utf-8')
    response['Content-Disposition'] = f'attachment; filename="driver_manifest_{driver.pk}.csv"'
    response.write('\ufeff')
    writer = csv.writer(response)
    writer.writerow(['Tracking number', 'Recipient', 'Recipient phone', 'Origin',
                     'Destination', 'Status', 'Weight (kg)', 'Expected delivery'])
    for shipment in shipments.iterator():
        writer.writerow([_excel_safe(value) for value in [
            shipment.tracking_number, shipment.recipient_name, shipment.recipient_phone,
            shipment.origin, shipment.destination, shipment.get_status_display(),
            shipment.weight_kg, shipment.expected_delivery or '',
        ]])
    return response
